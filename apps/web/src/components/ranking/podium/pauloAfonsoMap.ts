// Trecho leste/nordeste do contorno que acompanha o Rio São Francisco
// (divisa com Alagoas), do primeiro ponto até o extremo norte.
export const RIVER_BORDER_RANGE: [number, number] = [0, 26];

export const CITY_CENTER_LNG_LAT: [number, number] = [-38.2147, -9.4064];

const LNG_MIN = -38.5489;
const LNG_MAX = -37.9979;
const LAT_MIN = -9.7125;
const LAT_MAX = -9.353;
const LAT_SCALE = Math.cos((((LAT_MIN + LAT_MAX) / 2) * Math.PI) / 180);

export const MAP_ASPECT = ((LNG_MAX - LNG_MIN) * LAT_SCALE) / (LAT_MAX - LAT_MIN);

// Converte pra coordenadas do chão da cena, centralizadas, com `width` de largura.
// Norte fica pro fundo (-Z), leste pra direita (+X).
export function projectToMap(lng: number, lat: number, width: number): [number, number] {
  const depth = width / MAP_ASPECT;
  const x = ((lng - LNG_MIN) / (LNG_MAX - LNG_MIN) - 0.5) * width;
  const z = ((LAT_MAX - lat) / (LAT_MAX - LAT_MIN) - 0.5) * depth;
  return [x, z];
}
